"""Generate the reference pages in docs/reference/ from the code.

    uv run --no-sync python scripts/gen_reference.py           # rewrite the pages
    uv run --no-sync python scripts/gen_reference.py --check   # exit 1 when a page is out of date

Sources: the argument parser (`relaybay.cli.build_parser`), the `Settings` field metadata
(`relaybay.config`), the live MCP registry (`relaybay.mcp_server.server.build_mcp`) and the
policy schema and presets (`relaybay.policy`).
"""

import argparse
import asyncio
import difflib
import sys
import tempfile
from dataclasses import MISSING, fields
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference"
GENERATED = (
    "<!-- Generated by scripts/gen_reference.py from {source}; do not edit by hand."
    " CI fails when it is out of date. -->"
)


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


# --- CLI -------------------------------------------------------------------


def _option(action: argparse.Action) -> tuple[str, str, str]:
    names = ", ".join(f"`{n}`" for n in action.option_strings) or f"`{action.dest}`"
    if action.nargs == 0:
        value = ""
    elif action.choices:
        value = "`" + "\\|".join(str(c) for c in action.choices) + "`"
    else:
        value = f"`{action.metavar or action.dest.upper()}`"
    help_text = action.help or ""
    if action.required:
        help_text += " Required."
    if action.default not in (None, False, argparse.SUPPRESS) and action.choices:
        help_text += f" Default: `{action.default}`."
    return names, value, _cell(help_text)


def _options(command: argparse.ArgumentParser) -> list[str]:
    """The option table of one command; hidden options and nested commands are left out."""
    options = [
        a
        for a in command._actions
        if not isinstance(a, argparse._HelpAction | argparse._SubParsersAction)
        and a.help != argparse.SUPPRESS
    ]
    if not options:
        return ["No options."]
    lines = ["| Option | Value | Meaning |", "|---|---|---|"]
    return lines + ["| {} | {} | {} |".format(*_option(a)) for a in options]


def cli_page() -> str:
    from relaybay.cli import build_parser

    parser = build_parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {a.dest: a.help or "" for a in sub._choices_actions}
    lines = [
        GENERATED.format(source="the argument parser"),
        "",
        "# CLI reference",
        "",
        "`relaybay [--version] <command> [options]`; without a command, `serve` runs.",
        "`python -m relaybay` is the same. `relaybay <command> --help` prints the same options.",
        "",
        "| Command | What it does |",
        "|---|---|",
    ]
    lines += [f"| [`{name}`](#{name}) | {_cell(helps[name])} |" for name in sub.choices]
    for name, command in sub.choices.items():
        lines += ["", f"## `{name}`", "", _cell(helps[name]), ""]
        lines += _options(command)
        nested = [a for a in command._actions if isinstance(a, argparse._SubParsersAction)]
        for action in nested:
            nested_helps = {a.dest: a.help or "" for a in action._choices_actions}
            for child, parser in action.choices.items():
                lines += ["", f"### `{name} {child}`", "", _cell(nested_helps[child]), ""]
                lines += _options(parser)
    lines += [
        "",
        "## Exit codes",
        "",
        "| Code | Meaning |",
        "|---|---|",
        "| `0` | Success. |",
        "| `1` | A failed setup write, a failed check item (`setup --check`, `doctor`), `demo`"
        " refused a data folder that already holds a board, or `import` / `export` has an item"
        " refused, in conflict or failed; `desktop --quit` found no running program, or a"
        " second `desktop` found one that holds the lock but does not answer. |",
        "| `2` | Invalid settings or arguments; `desktop` without the `desktop` extra. |",
        "",
        "`relaybay hook` always exits `0`, so a hook never fails a Claude Code session.",
    ]
    return "\n".join(lines) + "\n"



def _default(f: Any) -> str:
    if f.metadata.get("default"):
        return f.metadata["default"]
    value = f.default if f.default is not MISSING else f.default_factory()
    if isinstance(value, bool):
        return f"`{str(value).lower()}`"
    return f"`{value}`"


def config_page() -> str:
    from relaybay.config import Settings

    lines = [
        GENERATED.format(source="the Settings fields in src/relaybay/config.py"),
        "",
        "# Configuration reference",
        "",
        "Settings come from defaults, then `config.toml` in the data directory, then `RELAYBAY_*`",
        "environment variables, then command-line flags (a later source wins). An invalid value",
        "stops `relaybay serve` with a message that names the key.",
        "",
        "## Settings",
        "",
        "| Key (`config.toml`) | Default | Environment | Flag | Meaning |",
        "|---|---|---|---|---|",
    ]
    for f in fields(Settings):
        meta = f.metadata
        if not meta:
            continue  # internal, not configurable
        cells = [
            f"`{meta['key']}`" if meta["key"] else "—",
            _default(f),
            f"`{meta['env']}`" if meta["env"] else "—",
            f"`{meta['flag']}`" if meta["flag"] else "—",
            meta["meaning"],
        ]
        lines.append("| " + " | ".join(_cell(c) for c in cells) + " |")
    lines += ["", "## Example `config.toml`", "", CONFIG_EXAMPLE, *desktop_section()]
    return "\n".join(lines) + "\n"


def desktop_section() -> list[str]:
    from relaybay.desktop.settings import DesktopSettings

    lines = [
        "",
        "## Desktop program (`desktop.toml`)",
        "",
        "`desktop.toml` lives in the per-user config folder (`platformdirs`: on Windows",
        "`%LOCALAPPDATA%\\relaybay`, on macOS `~/Library/Application Support/relaybay`, on",
        "Linux `~/.config/relaybay`), or in the folder `RELAYBAY_CONFIG_DIR` names. The program",
        "and the CLI both read it; `relaybay desktop config` shows and changes it. Beside it:",
        "`external-token` (0600, the external server's token), `window-state.json` (the board",
        "window's size, position and maximized flag, written by the program), `reopen-window` (a",
        "one-shot marker left when the program quits for an update with its window open),",
        "`notify_state.json` (where tray notifications have read up to, written by the program),",
        "`desktop-start.log` (the program's start journal, read by `relaybay doctor`) and the",
        "program's `desktop.lock` and `desktop.ipc`.",
        "",
        "The data folder is `--home`, else `RELAYBAY_HOME`, else `data_dir` here, else the",
        "per-user data dir.",
        "",
        "| Key | Default | Meaning |",
        "|---|---|---|",
    ]
    for f in fields(DesktopSettings):
        cells = [f"`{f.name}`", _default(f), f.metadata["meaning"]]
        lines.append("| " + " | ".join(_cell(c) for c in cells) + " |")
    return lines


# --- MCP -------------------------------------------------------------------


def _type(schema: dict[str, Any]) -> str:
    if "anyOf" in schema:
        return " or ".join(_type(s) for s in schema["anyOf"])
    kind = schema.get("type", "any")
    if kind == "array":
        return f"list of {_type(schema.get('items', {}))}"
    return str(kind)


def _parameters(schema: dict[str, Any]) -> list[str]:
    props = schema.get("properties", {})
    if not props:
        return ["No parameters."]
    required = set(schema.get("required", []))
    rows = ["| Parameter | Type | Required | Description |", "|---|---|---|---|"]
    for name, prop in props.items():
        description = prop.get("description", "")
        if "default" in prop and prop["default"] is not None:
            description += f" Default: `{prop['default']}`."
        need = "yes" if name in required else "no"
        rows.append(f"| `{name}` | {_type(prop)} | {need} | {_cell(description)} |")
    return rows


async def _registry() -> tuple[list[Any], list[Any], list[Any], list[Any]]:
    from relaybay.mcp_server.server import build_mcp
    from relaybay.service import Service

    with tempfile.TemporaryDirectory() as folder:
        mcp = build_mcp(Service(Path(folder) / "relaybay.sqlite"))
        return (
            await mcp.list_tools(),
            await mcp.list_resources(),
            await mcp.list_resource_templates(),
            await mcp.list_prompts(),
        )


def mcp_page() -> str:
    tools, resources, templates, prompts = asyncio.run(_registry())
    lines = [
        GENERATED.format(source="the live MCP tool registry"),
        "",
        "# MCP reference",
        "",
        "Every tool, prompt and resource the server registers, with the parameters and",
        "descriptions clients receive. How to use them together: [MCP tools](../mcp-tools.md).",
        "",
        "## Tools",
        "",
        "| Tool | Kind |",
        "|---|---|",
    ]
    for tool in tools:
        hints = tool.annotations
        kind = "read" if hints is not None and hints.read_only_hint else "write"
        lines.append(f"| [`{tool.name}`](#{tool.name}) | {kind} |")
    for tool in tools:
        lines += ["", f"### `{tool.name}`", "", _cell(tool.description or ""), ""]
        lines += _parameters(tool.input_schema)
    lines += ["", "## Resources", "", "| URI | Name | Type | Description |", "|---|---|---|---|"]
    entries = [(str(r.uri), r) for r in resources] + [(t.uri_template, t) for t in templates]
    for uri, item in sorted(entries, key=lambda e: e[0]):
        lines.append(
            f"| `{uri}` | {item.name} | {item.mime_type or ''} | {_cell(item.description or '')} |"
        )
    lines += ["", "## Prompts", "", "| Prompt | Arguments | Description |", "|---|---|---|"]
    for prompt in prompts:
        arguments = ", ".join(
            f"`{a.name}`" + ("" if a.required else "?") for a in prompt.arguments or []
        )
        lines.append(f"| `{prompt.name}` | {arguments} | {_cell(prompt.description or '')} |")
    return "\n".join(lines) + "\n"


# --- policy ----------------------------------------------------------------


def _schema_type(node: dict[str, Any], defs: dict[str, Any]) -> tuple[str, dict[str, Any]]:
    """A readable type of a schema node and the node behind its `$ref`."""
    if "$ref" in node:
        target = defs[node["$ref"].rsplit("/", 1)[-1]]
        merged = {**target, **{k: v for k, v in node.items() if k != "$ref"}}
        return _schema_type(merged, defs)
    if "enum" in node:
        values = ", ".join("`null`" if v is None else f"`{v}`" for v in node["enum"])
        return f"one of {values}", node
    kind = node.get("type", "any")
    if kind == "array":
        item, _ = _schema_type(node.get("items", {}), defs)
        limit = f", at most {node['maxItems']}" if "maxItems" in node else ""
        return f"list of {item}{limit}", node
    if kind == "string" and "maxLength" in node:
        return f"string (at most {node['maxLength']} characters)", node
    return str(kind), node


def _schema_rows(node: dict[str, Any], defs: dict[str, Any], prefix: str) -> list[str]:
    rows = []
    for name, prop in node.get("properties", {}).items():
        path = f"{prefix}{name}"
        kind, resolved = _schema_type(prop, defs)
        description = prop.get("description") or resolved.get("description", "")
        if resolved.get("type") == "object" and "properties" in resolved:
            rows.append(f"| `{path}` | object | {_cell(description)} |")
            rows += _schema_rows(resolved, defs, f"{path}.")
        else:
            rows.append(f"| `{path}` | {_cell(kind)} | {_cell(description)} |")
    return rows


POLICY_INTRO = """\
The policy decides what agents may do on each kind of environment, what the PreToolUse guard
counts as a change and what counts as a secret. Behaviour: [SPEC §7](../SPEC.md#spec-policy);
design: [0013](../design/0013-policy-as-data.md); a worked example:
[Full access on a trusted local machine](../how-to/trusted-machine.md).

## Layers

A later layer wins: the built-in **preset** named by the global layer → `[permission_defaults]`
and `guard_mode` from `config.toml` (legacy, only when set) → the **global** file
(`policy.json` in the data directory, setting `policy_file`) → the **project** layer → the
**environment** layer (both stored in the database, edited in Settings → Policy). The
environment's own level and per-capability overrides on Stands & access win over every layer.

Objects merge key by key; scalars and lists replace. A list key may also be written `key+` (add
items; a pattern with an existing `id` replaces it) or `key-` (remove items by value or `id`);
`key` is applied first, then `key+`, then `key-`. `$schema` and `description` are ignored;
`preset` is read from the global layer only.

The global file is read on start (a broken file stops `relaybay serve` with the path and the
problem) and again whenever it changes; a file that breaks later is logged, shown on the Policy
page, and the last valid version stays in effect. A broken project or environment layer is
logged and ignored.

Custom regular expressions (`guard.patterns[].command` / `change`, `secrets.allow`): at most 200
characters, no back-references, no quantified group holding a quantifier (`(a+)+`) or an
alternation (`(a|aa)*`), at most two unbounded quantifiers (`*`, `+`, `{n,}`), and fast on long
hostile input when the layer is loaded. They run case-insensitively with a hard time limit on at
most 8 KB of text; a call that times out fails closed (a guard pattern counts as matched, an
allow pattern does not allow) and is logged at most once a minute per pattern.

JSON Schema: [`policy.schema.json`](policy.schema.json) (the same file as
`src/relaybay/policy/schema.json`)."""


def policy_page() -> str:
    from relaybay import policy
    from relaybay.domain import guard
    from relaybay.domain.environments import DETECTOR_IDS

    spec = policy.schema()
    defs = spec["$defs"]
    lines = [
        GENERATED.format(source="src/relaybay/policy/schema.json and the presets"),
        "",
        "# Policy reference",
        "",
        POLICY_INTRO,
        "",
        "## Keys",
        "",
        "| Key | Type | Meaning |",
        "|---|---|---|",
        *_schema_rows(spec, defs, ""),
        "",
        "A custom pattern (`guard.patterns`, `guard.patterns+`):",
        "",
        "| Key | Type | Meaning |",
        "|---|---|---|",
        *_schema_rows(defs["patterns"]["items"], defs, ""),
        "",
        "## Built-in guard rules",
        "",
        "| Id | Capability | Reason says |",
        "|---|---|---|",
    ]
    lines += [f"| `{r.id}` | `{r.capability}` | {r.name} |" for r in guard.MUTATING_RULES]
    lines += [
        f"| `{guard.MCP_TOOL_RULE_ID}` | any | MCP tool whose name says it changes something |",
        "",
        "## Built-in secret detectors",
        "",
        ", ".join(f"`{d}`" for d in DETECTOR_IDS) + ".",
        "",
        "Switching a detector off affects only the check on write; the live-actions journal",
        "still masks every shape it knows.",
        "",
        "## Presets",
        "",
    ]
    for name in policy.PRESETS:
        body = policy.preset(name)
        lines += [
            f"### `{name}`",
            "",
            body.get("description", ""),
            "",
            "```json",
            policy.dump(body).rstrip("\n"),
            "```",
            "",
        ]
    return "\n".join(lines).rstrip("\n") + "\n"


def policy_schema() -> str:
    from relaybay import policy

    return policy.dump(policy.schema())


PAGES = {
    "cli.md": cli_page,
    "configuration.md": config_page,
    "mcp.md": mcp_page,
    "policy.md": policy_page,
    "policy.schema.json": policy_schema,
}


def render() -> dict[Path, str]:
    return {OUT / name: build() for name, build in PAGES.items()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="Fail if a page is out of date.")
    args = parser.parse_args(argv)
    sys.stdout.reconfigure(encoding="utf-8")  # diffs of UTF-8 pages on every OS
    stale = []
    for path, text in render().items():
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else ""
        if current == text:
            continue
        if args.check:
            stale.append(path)
            diff = difflib.unified_diff(
                current.splitlines(keepends=True),
                text.splitlines(keepends=True),
                fromfile=f"{path.name} (committed)",
                tofile=f"{path.name} (generated)",
            )
            sys.stdout.writelines(diff)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        names = ", ".join(p.relative_to(ROOT).as_posix() for p in stale)
        print(
            f"\nOut of date: {names}. Run: uv run python scripts/gen_reference.py", file=sys.stderr
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
